#!/usr/bin/env python3
"""Sync scripts for homebrew-craft-clis.

Scans storytold GitHub organization for macOS CLI releases,
generates Homebrew formulae, and updates the README table.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
from typing import Any
import urllib.error
import urllib.request
import concurrent.futures

ASSET_REGEX = re.compile(
    r"^(?P<cli_name>.+-cli)-(?P<version>.+)-macos-universal\.zip$"
)


@dataclass
class FormulaInfo:
    cli_name: str
    version: str
    repo_name: str
    desc: str
    homepage: str
    url: str
    sha256: str


def formula_class_name(formula_name: str) -> str:
    """Converts a formula name like 'craft-anything-cli' to 'CraftAnythingCli'."""
    parts = re.split(r"[-_.\s]+", formula_name)
    return "".join(part.capitalize() for part in parts if part)


def match_cli_asset(asset_name: str) -> tuple[str, str] | None:
    """Matches release asset against '*-cli-*-macos-universal.zip'."""
    match = ASSET_REGEX.match(asset_name)
    if not match:
        return None
    return match.group("cli_name"), match.group("version")


def parse_sha256sums(content: str) -> dict[str, str]:
    """Parses SHA256SUMS.txt content into a dict of {filename: sha256_hex}."""
    mapping: dict[str, str] = {}
    for line in content.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        match = re.match(r"^([a-fA-F0-9]{64})\s+[*]?(.+)$", line)
        if match:
            sha, filename = match.groups()
            mapping[filename.strip()] = sha.lower()
    return mapping


def clean_description(repo_name: str, desc: str | None, max_len: int = 80) -> str:
    """Cleans a repository description to adhere to Homebrew formula guidelines.

    Guidelines: under 80 chars, no trailing period, no formula name prefix, no leading article.
    """
    if not desc:
        return f"Headless CLI and MCP server for {repo_name}"

    s = desc.strip()
    s = re.sub(r"\.+$", "", s).strip()
    if ". " in s:
        s = s.split(". ")[0].strip()

    # Strip leading Product/Repo name prefix like "CADCraft: " or "WordCraft: "
    s = re.sub(r"^[\w\s-]+:\s*", "", s).strip()

    # Strip leading articles and boilerplates
    s = re.sub(
        r"^(?:an?\s+open-source(?:,?\s+clean-room)?\s+|an?\s+|the\s+)",
        "",
        s,
        flags=re.IGNORECASE,
    ).strip()

    if s:
        s = s[0].upper() + s[1:]

    # Truncate cleanly if exceeding max_len
    if len(s) > max_len:
        for sep in [" — ", "; ", " - "]:
            if sep in s:
                first_part = s.split(sep)[0].strip()
                if 20 <= len(first_part) <= max_len:
                    s = first_part
                    break
        if len(s) > max_len:
            s = s[: max_len - 3].rsplit(" ", 1)[0] + "..."

    return s.rstrip(" .")


def clean_homepage(homepage: str | None, org: str, repo_name: str) -> str:
    """Normalizes homepage URL with fallback to GitHub repo."""
    if homepage and homepage.strip().startswith(("http://", "https://")):
        return homepage.strip().rstrip("/")
    return f"https://github.com/{org}/{repo_name}"


def render_formula(info: FormulaInfo) -> str:
    """Renders a Homebrew Formula Ruby file following SPEC.md specifications."""
    class_name = formula_class_name(info.cli_name)
    desc_escaped = info.desc.replace('"', '\\"')

    return f"""# typed: false
# frozen_string_literal: true

# This file is auto-generated by scripts/sync.py. DO NOT EDIT MANUALLY.
class {class_name} < Formula
  desc "{desc_escaped}"
  homepage "{info.homepage}"
  url "{info.url}"
  version "{info.version}"
  sha256 "{info.sha256}"
  license any_of: ["MIT", "Apache-2.0"]

  depends_on :macos

  def install
    bin.install "{info.cli_name}"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/{info.cli_name} --version")
  end
end
"""


def render_readme_table(formulae: list[FormulaInfo]) -> str:
    """Generates the Markdown table of available CLI formulae."""
    lines = [
        "| CLI | Version | Description | Install Command |",
        "| --- | --- | --- | --- |",
    ]
    for item in sorted(formulae, key=lambda x: x.cli_name):
        formula_link = f"[`{item.cli_name}`](Formula/{item.cli_name}.rb)"
        version_code = f"`{item.version}`"
        install_cmd = f"`brew install JsonLee12138/craft-clis/{item.cli_name}`"
        lines.append(
            f"| {formula_link} | {version_code} | {item.desc} | {install_cmd} |"
        )
    return "\n".join(lines)


def update_readme_content(readme_content: str, table_content: str) -> tuple[str, bool]:
    """Replaces table content between <!-- FORMULAE-TABLE:START --> markers."""
    start_marker = "<!-- FORMULAE-TABLE:START -->"
    end_marker = "<!-- FORMULAE-TABLE:END -->"

    start_idx = readme_content.find(start_marker)
    end_idx = readme_content.find(end_marker)

    if start_idx == -1 or end_idx == -1 or start_idx > end_idx:
        raise ValueError(
            f"Could not find valid '{start_marker}' and '{end_marker}' markers in README."
        )

    before = readme_content[: start_idx + len(start_marker)]
    after = readme_content[end_idx:]

    new_content = f"{before}\n\n{table_content.strip()}\n\n{after}"
    changed = new_content != readme_content
    return new_content, changed


def filter_eligible_repos(
    repos: list[dict[str, Any]], exclude_repos: list[str]
) -> list[dict[str, Any]]:
    """Filters out archived and explicitly excluded repositories."""
    excluded_set = set(exclude_repos)
    return [
        r
        for r in repos
        if not r.get("archived", False) and r.get("name") not in excluded_set
    ]


def get_github_token() -> str | None:
    """Retrieves GitHub token from env or gh CLI if available."""
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        return token
    if shutil.which("gh"):
        try:
            res = subprocess.run(
                ["gh", "auth", "token"],
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
                text=True,
                timeout=3,
                check=True,
            )
            token = res.stdout.strip()
            if token:
                return token
        except Exception:
            pass
    return None


def github_request(
    url: str, token: str | None = None, is_json: bool = True
) -> Any:
    """Performs HTTP GET with standard headers."""
    headers = {
        "User-Agent": "homebrew-craft-clis-sync",
        "Accept": "application/vnd.github.v3+json",
    }
    if token:
        headers["Authorization"] = f"Bearer {token}"

    req = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(req, timeout=15) as resp:
        data = resp.read()
        if is_json:
            return json.loads(data.decode("utf-8"))
        return data.decode("utf-8")


def fetch_all_org_repos(
    org: str, token: str | None = None
) -> list[dict[str, Any]]:
    """Fetches all repositories for the organization using pagination."""
    repos: list[dict[str, Any]] = []
    page = 1
    while True:
        url = f"https://api.github.com/orgs/{org}/repos?per_page=100&page={page}"
        batch = github_request(url, token=token, is_json=True)
        if not batch:
            break
        repos.extend(batch)
        if len(batch) < 100:
            break
        page += 1
    return repos


def inspect_repo_release(
    repo: dict[str, Any], org: str, token: str | None
) -> FormulaInfo | None:
    """Checks the latest release of a repository and extracts FormulaInfo if eligible."""
    repo_name = repo["name"]
    release_url = (
        f"https://api.github.com/repos/{org}/{repo_name}/releases/latest"
    )

    try:
        rel = github_request(release_url, token=token, is_json=True)
    except urllib.error.HTTPError as err:
        if err.code == 404:
            return None
        print(f"[{repo_name}] HTTP error {err.code}: {err.reason}", file=sys.stderr)
        return None
    except Exception as err:
        print(f"[{repo_name}] Error fetching release: {err}", file=sys.stderr)
        return None

    if rel.get("draft") or rel.get("prerelease"):
        return None

    assets = rel.get("assets", [])
    cli_asset = None
    cli_name = None
    version = None
    sha_asset = None

    for asset in assets:
        name = asset.get("name", "")
        if name == "SHA256SUMS.txt":
            sha_asset = asset
        else:
            matched = match_cli_asset(name)
            if matched:
                cli_asset = asset
                cli_name, version = matched

    if not (cli_asset and sha_asset and cli_name and version):
        return None

    # Fetch SHA256SUMS.txt
    sha_download_url = sha_asset.get("browser_download_url")
    try:
        sha_text = github_request(sha_download_url, token=token, is_json=False)
        sha_map = parse_sha256sums(sha_text)
    except Exception as err:
        print(
            f"[{repo_name}] Failed to fetch/parse SHA256SUMS.txt: {err}",
            file=sys.stderr,
        )
        return None

    target_filename = cli_asset.get("name")
    sha256_hash = sha_map.get(target_filename)
    if not sha256_hash or len(sha256_hash) != 64:
        print(
            f"[{repo_name}] Missing or invalid SHA256 for asset '{target_filename}'",
            file=sys.stderr,
        )
        return None

    desc = clean_description(repo_name, repo.get("description"))
    homepage = clean_homepage(repo.get("homepage"), org, repo_name)
    download_url = cli_asset.get("browser_download_url")

    return FormulaInfo(
        cli_name=cli_name,
        version=version,
        repo_name=repo_name,
        desc=desc,
        homepage=homepage,
        url=download_url,
        sha256=sha256_hash,
    )


def sync(config_path: Path, root_dir: Path, dry_run: bool = False) -> int:
    """Main synchronization routine."""
    with open(config_path, "r", encoding="utf-8") as f:
        config = json.load(f)

    org = config.get("org", "storytold")
    exclude_repos = config.get("exclude_repos", [])

    token = get_github_token()
    if not token:
        print(
            "WARNING: No GITHUB_TOKEN or 'gh' authentication detected. API rate limit is 60 req/hr.",
            file=sys.stderr,
        )

    print(f"Scanning organization '{org}' for repositories...")
    repos = fetch_all_org_repos(org, token=token)
    eligible = filter_eligible_repos(repos, exclude_repos)
    print(
        f"Found {len(repos)} total repos; {len(eligible)} eligible after filtering."
    )

    discovered: list[FormulaInfo] = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as executor:
        future_to_repo = {
            executor.submit(
                inspect_repo_release, repo, org, token
            ): repo["name"]
            for repo in eligible
        }
        for future in concurrent.futures.as_completed(future_to_repo):
            info = future.result()
            if info:
                discovered.append(info)

    discovered.sort(key=lambda x: x.cli_name)
    print(f"Discovered {len(discovered)} CLI products with valid releases.")

    formula_dir = root_dir / "Formula"
    formula_dir.mkdir(parents=True, exist_ok=True)

    # Process exclude_repos deletion
    for ex_repo in exclude_repos:
        formula_candidate = formula_dir / f"{ex_repo}-cli.rb"
        if formula_candidate.exists():
            if dry_run:
                print(f"[dry-run] Would remove excluded formula: {formula_candidate}")
            else:
                formula_candidate.unlink()
                print(f"Removed excluded formula: {formula_candidate}")

    updated_count = 0
    created_count = 0
    unchanged_count = 0

    for item in discovered:
        target_file = formula_dir / f"{item.cli_name}.rb"
        formula_code = render_formula(item)

        if target_file.exists():
            existing_code = target_file.read_text(encoding="utf-8")
            if existing_code == formula_code:
                unchanged_count += 1
                continue
            updated_count += 1
            action = "Updating"
        else:
            created_count += 1
            action = "Creating"

        if dry_run:
            print(f"[dry-run] {action} {target_file.name} (v{item.version})")
        else:
            target_file.write_text(formula_code, encoding="utf-8")
            print(f"{action} {target_file.name} (v{item.version})")

    # Update README.md
    readme_path = root_dir / "README.md"
    if readme_path.exists():
        table_content = render_readme_table(discovered)
        current_readme = readme_path.read_text(encoding="utf-8")
        try:
            new_readme, changed = update_readme_content(
                current_readme, table_content
            )
            if changed:
                if dry_run:
                    print("[dry-run] Would update README.md table.")
                else:
                    readme_path.write_text(new_readme, encoding="utf-8")
                    print("Updated README.md product table.")
            else:
                print("README.md table is already up to date.")
        except ValueError as err:
            print(f"Warning: {err}", file=sys.stderr)

    print(
        f"Summary: {created_count} created, {updated_count} updated, {unchanged_count} unchanged."
    )
    return 0


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Sync storytold CLI releases with Homebrew Tap"
    )
    parser.add_argument(
        "--config",
        type=Path,
        default=Path("config.json"),
        help="Path to config.json",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Simulate sync without writing files",
    )
    args = parser.parse_args()

    root_dir = Path(__file__).resolve().parent.parent
    config_path = root_dir / args.config if not args.config.is_absolute() else args.config

    if not config_path.exists():
        print(f"Error: config file not found at {config_path}", file=sys.stderr)
        sys.exit(1)

    exit_code = sync(config_path=config_path, root_dir=root_dir, dry_run=args.dry_run)
    sys.exit(exit_code)


if __name__ == "__main__":
    main()
